/**
 * Signing material lives outside the repository. When `keystore.properties` exists in the
 * project root (storeFile, storePassword, keyAlias, keyPassword) every build is signed with it,
 * so updates install over each other; otherwise the machine's debug key is used.
 */
val signingProps = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "app.drop"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.drop"
        minSdk = 26
        targetSdk = 35
        versionCode = 11
        versionName = "0.11.0"
    }

    signingConfigs {
        if (signingProps.isNotEmpty()) {
            create("drop") {
                storeFile = rootProject.file(signingProps.getProperty("storeFile"))
                storePassword = signingProps.getProperty("storePassword")
                keyAlias = signingProps.getProperty("keyAlias")
                keyPassword = signingProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            signingConfigs.findByName("drop")?.let { signingConfig = it }
        }
        release {
            isMinifyEnabled = false
            signingConfigs.findByName("drop")?.let { signingConfig = it }
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                it.forkEvery = 1
                it.maxHeapSize = "2g"
            }
        }
    }
}

